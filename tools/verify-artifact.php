<?php
declare(strict_types=1);

/**
 * Release verification helper (checklist step 5): extract a
 * COMPLETE-UPLOAD artifact into a clean directory, provision it as a
 * working site (config, installed lock, migrations, owner admin, home
 * page), and print the docroot + instructions for serving it.
 *
 * Uses the development SQLite driver because this verification runs
 * without a MySQL server — production installs are always MySQL/MariaDB
 * (documented in COMPATIBILITY.md). Everything else is the real artifact:
 * extracted files, real migrations, real app boot.
 *
 * Usage:
 *   php tools/verify-artifact.php dist/Website-Core-*-COMPLETE-UPLOAD.zip [outdir]
 *   php -S 127.0.0.1:PORT -t <printed docroot> <repo>/tools/dev-router.php
 */

$zipPath = $argv[1] ?? null;
if ($zipPath === null || !is_file($zipPath)) {
    fwrite(STDERR, "usage: php tools/verify-artifact.php <COMPLETE-UPLOAD.zip> [outdir]\n");
    exit(1);
}
$zipPath = realpath($zipPath);
$outDir = $argv[2] ?? (sys_get_temp_dir() . '/wc-host-' . bin2hex(random_bytes(4)));

// --- extract --------------------------------------------------------------
$zip = new ZipArchive();
if ($zip->open($zipPath, ZipArchive::RDONLY) !== true) {
    fwrite(STDERR, "cannot open {$zipPath}\n");
    exit(1);
}
@mkdir($outDir, 0777, true);
$zip->extractTo($outDir);
$zip->close();
echo "extracted to {$outDir}\n";

foreach (['index.php', 'includes/bootstrap.php', 'vendor/autoload.php', 'themes/base/theme.json', 'database/migrations'] as $need) {
    if (!file_exists($outDir . '/' . $need)) {
        fwrite(STDERR, "artifact missing required member: {$need}\n");
        exit(1);
    }
}
echo "required members present\n";

// --- config ---------------------------------------------------------------
$port = (int) (getenv('WC_VERIFY_PORT') ?: 18743);
$baseUrl = "http://127.0.0.1:{$port}";
@mkdir($outDir . '/config', 0777, true);
@mkdir($outDir . '/storage', 0777, true);
@mkdir($outDir . '/upload', 0777, true);
$config = <<<'PHP'
<?php
// Generated by tools/verify-artifact.php — dev-driver verification config.
return [
    'app' => [
        'name' => 'Artifact Verification Site', 'env' => 'development',
        'url' => '__BASEURL__', 'timezone' => 'UTC', 'locale' => 'en',
        'debug' => true, 'version' => '1.0.1', 'api_version' => 1,
    ],
    'database' => [
        'driver' => 'sqlite',
        'name' => '__STORAGE__/dev.sqlite',
        'prefix' => 'wc_',
    ],
    'paths' => [
        'storage' => '__STORAGE__',
        'upload' => '__ROOT__/upload',
    ],
    'security' => [
        'app_key' => '__APPKEY__', 'session_name' => 'WCSID',
        'session_idle' => 7200, 'session_absolute' => 43200,
        'cookie_secure' => 'never', 'trusted_proxies' => [],
    ],
    'mail' => ['transport' => 'capture', 'from' => 'no-reply@verify.local', 'from_name' => 'Verify'],
    'updates' => ['trust_roots' => [], 'channel' => 'stable'],
    'trust' => ['public_keys' => [], 'allow_unsigned' => true],
];
PHP;
$config = strtr($config, [
    '__BASEURL__' => $baseUrl,
    '__STORAGE__' => $outDir . '/storage',
    '__ROOT__' => $outDir,
    '__APPKEY__' => bin2hex(random_bytes(32)),
]);
file_put_contents($outDir . '/config/config.php', $config);
file_put_contents($outDir . '/config/installed.lock', date('c') . " install complete\n");
echo "config written (dev sqlite driver)\n";

// --- migrate + seed using the EXTRACTED code ------------------------------
$script = <<<'PHP'
<?php
$app = require '__ROOT__/includes/bootstrap.php';
$config = new Core\Config('__ROOT__/config/config.php');
$db = Core\Database\Connection::sqlite($config->get('database.name'), $config->get('database.prefix'));
(new Core\Database\Migrator($db, '__ROOT__/database/migrations'))->migrate();
$db->insert('admins', [
    'username' => 'owner', 'email' => 'owner@verify.local',
    'password_hash' => password_hash('verify-pass-1', PASSWORD_DEFAULT),
    'role' => 'owner', 'mfa_enabled' => 0, 'disabled' => 0,
    'created_at' => date('Y-m-d H:i:s'),
]);
$db->insert('pages', [
    'slug' => 'home', 'title' => 'Verification Home',
    'body' => '<p>Artifact verification page — the extracted package boots.</p>',
    'status' => 'published', 'created_at' => date('Y-m-d H:i:s'),
    'updated_at' => date('Y-m-d H:i:s'),
]);
$settings = new Core\Settings\SettingsRepository($db);
$settings->set('site.name', 'Artifact Verification Site');
$settings->set('site.home_slug', 'home');
$settings->set('system.cron_token', bin2hex(random_bytes(24)));
echo "migrated + seeded\n";
PHP;
$script = strtr($script, ['__ROOT__' => $outDir]);
$seedFile = $outDir . '/storage/verify-seed.php';
file_put_contents($seedFile, $script);
$out = [];
exec('"' . PHP_BINARY . '" ' . escapeshellarg($seedFile) . ' 2>&1', $out, $code);
echo implode("\n", $out) . "\n";
if ($code !== 0 || !str_contains(implode("\n", $out), 'migrated + seeded')) {
    fwrite(STDERR, "migrate/seed failed\n");
    exit(1);
}

echo "\nDOCROOT={$outDir}\n";
echo "serve:  php -S 127.0.0.1:{$port} -t \"{$outDir}\" tools/dev-router.php\n";
echo "login:  owner / verify-pass-1  at {$baseUrl}/admin\n";
